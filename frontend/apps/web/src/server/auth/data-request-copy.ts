export type DataRequestKey = (typeof dataRequestKeys)[number];
export type DataRequestCopy = (key: DataRequestKey) => string;
export type DataRequestCatalogues = Readonly<{ en: unknown; tr: unknown }>;

/**
 * Native startup supplies the same authored JSON the catalogue tests validate. A missing, extra, empty, oversized or
 * parameterized message refuses startup: this document interpolates nothing, so numbers and dates stand apart.
 */
export function prepareDataRequestCatalogues(catalogues: DataRequestCatalogues) {
  const prepared = new Map<'en' | 'tr', ReadonlyMap<DataRequestKey, string>>();
  for (const locale of ['en', 'tr'] as const) {
    const values = new Map<DataRequestKey, string>();
    const visit = (value: unknown, prefix = '') => {
      if (!value || typeof value !== 'object' || Array.isArray(value))
        throw new Error('Data request catalogue unavailable');
      for (const [key, child] of Object.entries(value)) {
        const path = prefix ? prefix + '.' + key : key;
        if (typeof child === 'string') {
          if (
            !dataRequestKeys.includes(path as DataRequestKey) ||
            !child.trim() ||
            child.length > 1000 ||
            /[{}<>]/.test(child) ||
            child.includes(String.fromCharCode(0))
          )
            throw new Error('Data request catalogue unavailable');
          values.set(path as DataRequestKey, child);
        } else visit(child, path);
      }
    };
    visit(catalogues[locale]);
    if (values.size !== dataRequestKeys.length)
      throw new Error('Data request catalogue unavailable');
    prepared.set(locale, values);
  }
  /** Turkish for an Accept-Language whose first range is Turkish, as the consent entry decides; else English. */
  return (acceptLanguage: string | null) => {
    const locale = /^tr(?:[-,; ]|$)/i.test(acceptLanguage ?? '') ? 'tr' : 'en';
    const messages = prepared.get(locale)!;
    const phrase: DataRequestCopy = (key) =>
      messages.get(key) ?? messages.get('error.unavailable')!;
    return Object.freeze({ locale, phrase });
  };
}
