// Closed fault and gate selections in generated copies of the actual owner/Next graph.
import assert from 'node:assert/strict';

export const ownershipMatrixCases = Object.freeze([
  'ready-term',
  'ready-int',
  'prepare-term',
  'prepare-int',
  'prepare-watchdog',
  'registration-release',
  'registration-watchdog',
  'prehello-term',
  'prehello-int',
  'prehello-child-term',
  'prehello-child-int',
  'prehello-owner-death',
  'prepare-owner-death',
  'prepare-disconnect',
  'worker-positive',
  'worker-exit-zero',
  'worker-exit-one',
  'worker-self-kill',
  'worker-ordered-stop',
  'worker-owner-death',
]);

function replace(source, needle, value) {
  assert.equal(source.split(needle).length, 2, 'unique matrix instrumentation anchor');
  return source.replace(needle, value);
}

const observations = `
import { appendFileSync as ownershipAppend, existsSync as ownershipExists, readFileSync as ownershipRead, writeFileSync as ownershipWrite } from 'node:fs';
import { resolve as ownershipResolve } from 'node:path';
const ownershipDirectory = ownershipResolve(process.cwd(), '../../../ownership-control');
const ownershipCase = ownershipExists(ownershipResolve(ownershipDirectory, 'scenario')) ? ownershipRead(ownershipResolve(ownershipDirectory, 'scenario'), 'utf8') : 'build';
if (![...${JSON.stringify(ownershipMatrixCases)}, 'build'].includes(ownershipCase)) throw new Error('Closed ownership scenario refused');
const ownershipStarted = performance.now();
function ownershipEvent(event: string) {
  ownershipAppend(ownershipResolve(ownershipDirectory, 'events.jsonl'), JSON.stringify({event, case: ownershipCase, pid: process.pid, parentPid: process.ppid, milliseconds: Math.round(performance.now() - ownershipStarted)}) + '\\n', {mode: 0o600});
}
async function ownershipGate(name: string) {
  while (!ownershipExists(ownershipResolve(ownershipDirectory, name + '.release'))) await new Promise((resolve) => setTimeout(resolve, 10));
}
`;
const javascriptObservations = observations
  .replace('event: string', 'event')
  .replace('name: string', 'name');

/** Every selector and mutation is literal; controls are outside all framework input trees. */
export function instrumentFrameworkOwnershipMatrix({
  configuration,
  runtime,
  child,
  owner,
  rootPage,
}) {
  // Match the product public layout's request-local rendering shape. The worker
  // route below remains static; every generated byte enters the genuine build graph.
  const minimalRoot = 'export default function Page() { return <main>Public</main>; }';
  assert.equal(rootPage, minimalRoot, 'exact copied ownership root page');
  rootPage = "export const dynamic = 'force-dynamic';\nexport const revalidate = 0;\n" + rootPage;
  configuration = observations + configuration;
  configuration = replace(
    configuration,
    'export default nextConfig;',
    `export default async function configuration(phase: string) {
  if (['phase-production-server', 'phase-development-server'].includes(phase) && ownershipCase.startsWith('prepare-') && !ownershipExists(ownershipResolve(ownershipDirectory, 'prepare.entered'))) {
    ownershipWrite(ownershipResolve(ownershipDirectory, 'prepare.entered'), '', {flag: 'wx', mode: 0o600});
    ownershipEvent('prepare-entered');
    await ownershipGate('prepare');
    ownershipEvent('prepare-released');
  }
  return nextConfig;
}`,
  );
  runtime = javascriptObservations + runtime;
  runtime = replace(
    runtime,
    'export async function startPublicRuntime(control) {',
    `export async function startPublicRuntime(control) {
  ownershipEvent('native-imported');
  control.proof.onWatchdog(() => ownershipEvent('watchdog'));
  if (ownershipCase.startsWith('registration-')) {
    ownershipEvent('registration-entered');
    while (!control.stopRequested()) await new Promise((resolve) => setTimeout(resolve, 10));
    ownershipEvent('registration-stop-latched');
    await ownershipGate('registration');
    ownershipEvent('registration-released');
  }
  if (['prepare-disconnect', 'prepare-watchdog', 'worker-exit-zero', 'worker-exit-one', 'worker-self-kill'].includes(ownershipCase)) {
    void (async () => {
      await ownershipGate('fault');
      ownershipEvent('direct-fault');
      if (ownershipCase === 'prepare-watchdog') process.kill(process.pid, 'SIGINT');
      else if (ownershipCase === 'prepare-disconnect') process.disconnect();
      else if (ownershipCase === 'worker-exit-zero') process.exit(0);
      else if (ownershipCase === 'worker-exit-one') process.exit(1);
      else process.kill(process.pid, 'SIGKILL');
    })();
  }`,
  );
  runtime = replace(
    runtime,
    '  control.registerShutdown(shutdown);',
    `  control.registerShutdown(async () => {
    await shutdown();
    if (ownershipCase === 'registration-watchdog') await ownershipGate('shutdown');
  });`,
  );
  runtime = replace(
    runtime,
    '    stopping = true;',
    "    stopping = true;\n    if (!control.stopRequested()) throw new Error('Ownership stop was not consumed');\n    ownershipEvent('stop-consumed');",
  );
  runtime = replace(
    runtime,
    '    await ownSetup(app.prepare());',
    `    ownershipEvent('prepare-called');
    try { await ownSetup(app.prepare()); } finally { ownershipEvent('prepare-settled'); }`,
  );
  runtime = replace(
    runtime,
    '      ownShutdown(() => admission.shutdown());',
    "      ownershipEvent('admission-stop');\n      ownShutdown(() => admission.shutdown());",
  );
  runtime = replace(
    runtime,
    '      ownShutdown(() => bffRequests.stop());',
    "      ownershipEvent('requests-stop');\n      ownShutdown(() => bffRequests.stop());",
  );
  runtime = replace(
    runtime,
    '      ownShutdown(() => bffSessions.stop());',
    "      ownershipEvent('sessions-stop');\n      ownShutdown(() => bffSessions.stop());",
  );
  runtime = replace(
    runtime,
    'if (app) ownShutdown(() => app.close());',
    `if (app) ownShutdown(() => {
        ownershipEvent('next-close-called');
        return Promise.resolve(app.close()).then(() => ownershipEvent('next-close-settled'));
      });`,
  );
  runtime = replace(
    runtime,
    "          server.listen(0, '127.0.0.1', () => {",
    "          ownershipEvent('native-listen');\n          server.listen(0, '127.0.0.1', () => {",
  );
  child = javascriptObservations + child;
  child = replace(
    child,
    '  child = createFrameworkRuntimeChildControl();',
    `  child = createFrameworkRuntimeChildControl();
  if (ownershipCase.startsWith('prehello-')) {
    process.on('message', (message) => { if (message?.kind === 'stop') ownershipEvent('prehello-stop-observed'); });
    process.on('SIGTERM', () => ownershipEvent('prehello-signal-observed'));
    process.on('SIGINT', () => ownershipEvent('prehello-signal-observed'));
    process.once('disconnect', () => ownershipEvent('prehello-parent-lost'));
    ownershipEvent('prehello-entered');
    if (ownershipCase === 'prehello-child-term') process.kill(process.pid, 'SIGTERM');
    if (ownershipCase === 'prehello-child-int') process.kill(process.pid, 'SIGINT');
    await ownershipGate('prehello');
    ownershipEvent('prehello-released');
  }`,
  );
  owner = javascriptObservations + owner;
  owner = replace(
    owner,
    '  const graceful =',
    `  ownershipWrite(ownershipResolve(ownershipDirectory, 'owner-receipt.json'), JSON.stringify(receipt), {flag: 'wx', mode: 0o600});
  ownershipEvent('owner-receipt');
  const graceful =`,
  );
  const page = `${observations}
export async function generateStaticParams() {
  if (process.env.NODE_ENV === 'development' && ownershipCase.startsWith('worker-')) {
    ownershipEvent('worker-entered');
    await ownershipGate('worker');
    ownershipEvent('worker-returned');
  }
  return [{slug: 'ownership'}];
}
export default function Page() { return <main>Owned static paths worker</main>; }
`;
  return Object.freeze({ configuration, runtime, child, owner, rootPage, page });
}
