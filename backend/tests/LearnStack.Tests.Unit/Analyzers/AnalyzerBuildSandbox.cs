using System.Diagnostics;
using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace LearnStack.Tests.Unit.Analyzers;

/// <summary>
/// Copies the real build hierarchy outside the repository, including the analyzer project
/// and its linked matcher. Local package archives supply an isolated restore; the proof
/// does not make a production restore or vulnerability-audit claim.
/// </summary>
internal sealed class AnalyzerBuildSandbox : IDisposable
{
    private const string ProbeSource = """
        namespace BuildProof;

        internal static class Probe
        {
            internal static void SensitiveMessage(string refreshToken) =>
                throw new System.InvalidOperationException(refreshToken);

            internal static void Invariant() =>
                throw new LearnStack.SharedKernel.Errors.DomainException("Fixed invariant.");
        }
        """;

    private const string DomainExceptionSource = """
        // <auto-generated />
        namespace LearnStack.SharedKernel.Errors;

        public sealed class DomainException : System.Exception
        {
            public DomainException(string message) : base(message) { }
        }
        """;

    private readonly string _root = Path.Combine(Path.GetTempPath(), "learnstack-analyzer-build-" + Guid.NewGuid().ToString("N"));
    private readonly string _backend;
    private readonly string _nugetConfig;

    public AnalyzerBuildSandbox()
    {
        _backend = Path.Combine(_root, "backend");
        _nugetConfig = Path.Combine(_root, "NuGet.Config");
        Directory.CreateDirectory(_backend);

        try
        {
            var repository = FindRepository();
            foreach (var relative in new[]
            {
                "backend/Directory.Build.props",
                "backend/Directory.Packages.props",
                "backend/.editorconfig",
                "backend/global.json",
                "backend/src/Directory.Build.props",
                "backend/src/Modules/Directory.Build.props",
                "backend/src/LearnStack.SharedKernel/Secrets/SensitiveTokenMatcher.cs",
            })
            {
                CopyFile(repository, relative);
            }

            var analyzer = Path.Combine(repository, "backend", "analyzers", "LearnStack.Analyzers");
            foreach (var file in Directory.EnumerateFiles(analyzer, "*", SearchOption.AllDirectories)
                .Where(file => Path.GetExtension(file) is ".cs" or ".csproj" or ".md")
                .Where(file => !Path.GetRelativePath(analyzer, file).Split(Path.DirectorySeparatorChar)
                    .Any(segment => segment is "bin" or "obj")))
            {
                CopyFile(repository, Path.GetRelativePath(repository, file));
            }

            WriteLocalPackageSources(Path.Combine(analyzer, "obj", "project.assets.json"));
        }
        catch
        {
            Dispose();
            throw;
        }
    }

    public string CreateProductionProject(string layer, bool violation = true)
    {
        var name = "LearnStack.BuildProof." + layer;
        var parent = layer is "Domain" or "Application"
            ? Path.Combine(_backend, "src", "Modules", "BuildProof")
            : Path.Combine(_backend, "src", "Future", "Deeply", "Nested");
        var directory = Path.Combine(parent, name);
        Directory.CreateDirectory(directory);

        // No TargetFramework, warning policy, scope property or analyzer reference is
        // restated here: the copied production hierarchy must supply all of them.
        var project = Path.Combine(directory, name + ".csproj");
        File.WriteAllText(project, "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        File.WriteAllText(Path.Combine(directory, "Probe.cs"), violation ? ProbeSource : """
            namespace BuildProof;
            internal static class Probe
            {
                internal static void FixedMessage(string className) => throw new System.InvalidOperationException(className);
            }
            """);
        File.WriteAllText(Path.Combine(directory, "DomainException.g.cs"), DomainExceptionSource);
        return project;
    }

    public string CreateExcludedProject(string tree)
    {
        var directory = Path.Combine(_backend, tree, "LearnStack.BuildProof." + tree);
        Directory.CreateDirectory(directory);
        var project = Path.Combine(directory, "LearnStack.BuildProof." + tree + ".csproj");
        File.WriteAllText(project, "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        File.WriteAllText(Path.Combine(directory, "Probe.cs"), ProbeSource);
        File.WriteAllText(Path.Combine(directory, "DomainException.g.cs"), DomainExceptionSource);
        return project;
    }

    public async Task RestoreAsync(string project)
    {
        var result = await RunAsync("restore", project, "--configfile", _nugetConfig,
            "--packages", Path.Combine(_root, "packages"),
            "--nologo", "--verbosity", "quiet", "--disable-parallel");

        if (result.ExitCode != 0)
        {
            throw new InvalidOperationException("The disposable local-package restore failed. " + result.Summary);
        }
    }

    public Task<AnalyzerBuildResult> BuildAsync(string project) => RunAsync(
        "build", project, "--no-restore", "--nologo", "--verbosity", "quiet",
        "--disable-build-servers", "-maxcpucount:1");

    public static void AddOrdinaryCompilerWarning(string project) => File.AppendAllText(
        Path.Combine(Path.GetDirectoryName(project)!, "Probe.cs"),
        """


        internal static class OrdinaryCompilerWarning
        {
            internal static void Warn()
            {
                int unused = 0;
            }
        }
        """);

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private void CopyFile(string repository, string relative)
    {
        var destination = Path.Combine(_root, relative);
        Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
        File.Copy(Path.Combine(repository, relative), destination);
    }

    private void WriteLocalPackageSources(string assetsFile)
    {
        using var assets = JsonDocument.Parse(File.ReadAllText(assetsFile));
        var folders = assets.RootElement.GetProperty("packageFolders")
            .EnumerateObject().Select(folder => folder.Name).ToArray();

        if (folders.Length == 0 || folders.Any(folder => !Directory.Exists(folder)))
        {
            throw new InvalidOperationException("The built analyzer has no usable local package archive cache.");
        }

        new XDocument(new XElement("configuration",
            new XElement("packageSources",
                new XElement("clear"),
                folders.Select((folder, index) => new XElement("add",
                    new XAttribute("key", "cache-" + index.ToString(CultureInfo.InvariantCulture)),
                    new XAttribute("value", folder)))),
            new XElement("auditSources", new XElement("clear"))))
            .Save(_nugetConfig);
    }

    private async Task<AnalyzerBuildResult> RunAsync(params string[] arguments)
    {
        var start = new ProcessStartInfo("dotnet")
        {
            WorkingDirectory = _backend,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        };
        foreach (var argument in arguments)
        {
            start.ArgumentList.Add(argument);
        }

        start.Environment["CI"] = "true";
        start.Environment["DOTNET_CLI_HOME"] = Path.Combine(_root, "cli-home");
        start.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        start.Environment["DOTNET_CLI_WORKLOAD_UPDATE_NOTIFY_DISABLE"] = "true";
        start.Environment["DOTNET_NOLOGO"] = "1";
        start.Environment["MSBUILDDISABLENODEREUSE"] = "1";
        start.Environment["MSBUILDTERMINALLOGGER"] = "off";

        using var process = Process.Start(start)
            ?? throw new InvalidOperationException("The disposable dotnet process did not start.");
        var stdout = process.StandardOutput.ReadToEndAsync();
        var stderr = process.StandardError.ReadToEndAsync();
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(2));

        try
        {
            await process.WaitForExitAsync(timeout.Token);
        }
        catch (OperationCanceledException) when (timeout.IsCancellationRequested)
        {
            process.Kill(entireProcessTree: true);
            await process.WaitForExitAsync();
            await Task.WhenAll(stdout, stderr);
            throw new InvalidOperationException("The disposable dotnet process exceeded its time limit.");
        }

        var output = await stdout + Environment.NewLine + await stderr;
        // Keep failures useful without echoing restored cache paths, source expressions,
        // environment values or arbitrary package/SDK messages into test output.
        var diagnostics = Regex.Matches(output, @"\b(warning|error) ([A-Z]+[0-9]+)\b", RegexOptions.CultureInvariant)
            .Select(match => (Severity: match.Groups[1].Value, Id: match.Groups[2].Value))
            .Distinct().ToArray();
        return new AnalyzerBuildResult(process.ExitCode, diagnostics);
    }

    private static string FindRepository()
    {
        for (var current = new DirectoryInfo(AppContext.BaseDirectory); current is not null; current = current.Parent)
        {
            if (File.Exists(Path.Combine(current.FullName, "CLAUDE.md"))
                && File.Exists(Path.Combine(current.FullName, "backend", "Directory.Build.props")))
            {
                return current.FullName;
            }
        }

        throw new InvalidOperationException("The analyzer build proof could not locate the repository.");
    }
}

internal sealed record AnalyzerBuildResult(int ExitCode, (string Severity, string Id)[] Diagnostics)
{
    public bool HasDiagnostic(string severity, string id) => Diagnostics.Contains((severity, id));

    public string Summary => string.Create(CultureInfo.InvariantCulture,
        $"Exit code {ExitCode}; diagnostics: {string.Join(", ", Diagnostics.Select(item => item.Severity + " " + item.Id))}.");
}
